// --- THÈME (appliqué immédiatement via l'inline script dans <head>, ici on met à jour l'icône) ---
function toggleTheme() {
    const currentTheme = document.documentElement.getAttribute('data-theme');
    const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', newTheme);
    localStorage.setItem('theme', newTheme);
    updateThemeIcon(newTheme);
}

function updateThemeIcon(theme) {
    const icon = document.querySelector('.theme-toggle i');
    if (icon) icon.className = theme === 'dark' ? 'fas fa-sun' : 'fas fa-moon';
}

// --- LANGUES ---
function applyLang(lang) {
    const t = i18n[lang];
    if (!t) return;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!t[key]) return;
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = t[key];
        } else {
            el.innerHTML = t[key];
        }
    });
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active-lang', btn.id === 'btn-' + lang);
    });
}

function setLang(lang) {
    localStorage.setItem('lang', lang);
    applyLang(lang);
}

// --- PARTAGE (délégation d'événement — fonctionne aussi sur les boutons créés dynamiquement) ---
function shareCurrentPage() {
    const lang = localStorage.getItem('lang') || 'fr';
    const shareData = {
        title: 'Antiochian Orthodox Geneva',
        text: i18n[lang]['welcome-title'] || 'Église Orthodoxe Antiochienne — Genève',
        url: window.location.href
    };
    if (navigator.share) {
        navigator.share(shareData).catch(() => {});
    } else {
        navigator.clipboard.writeText(window.location.href).then(() => {
            const msg = (lang === 'ar') ? 'تم نسخ الرابط!' : (lang === 'en') ? 'Link copied!' : 'Lien copié !';
            showToast(msg);
        });
    }
}

function showToast(msg) {
    let toast = document.getElementById('share-toast');
    if (!toast) {
        toast = document.createElement('div');
        toast.id = 'share-toast';
        toast.style.cssText = 'position:fixed;bottom:90px;left:50%;transform:translateX(-50%);background:var(--gold-color);color:var(--primary-color);padding:10px 24px;border-radius:50px;font-weight:700;font-size:0.85rem;z-index:99999;opacity:0;transition:opacity 0.3s;pointer-events:none;';
        document.body.appendChild(toast);
    }
    toast.textContent = msg;
    toast.style.opacity = '1';
    setTimeout(() => { toast.style.opacity = '0'; }, 2500);
}

