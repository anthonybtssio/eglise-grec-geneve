function applyLang(lang) {
    const t = i18n[lang];
    if (!t) return;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = t[key];
            else el.innerHTML = t[key];
        }
    });
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.toggle('active-lang', btn.id === 'btn-' + lang));
}

function setLang(lang) {
    localStorage.setItem('lang', lang);
    applyLang(lang);
}

document.addEventListener("DOMContentLoaded", function() {
    applyLang(localStorage.getItem('lang') || 'fr');

    // PWA & Popup
    let deferredPrompt;
    const btnInstall = document.getElementById('btnInstall');
    const popup = document.getElementById('installPopup');
    const isIOS = /iPad|iPhone|iPod/.test(navigator.userAgent) && !window.MSStream;

    window.addEventListener('beforeinstallprompt', (e) => {
        e.preventDefault();
        deferredPrompt = e;
        if (btnInstall) btnInstall.style.display = 'block';
    });

    if (btnInstall) {
        btnInstall.style.display = 'block'; // Toujours visible au début
        btnInstall.addEventListener('click', () => {
            if (popup) popup.style.display = 'flex';
        });
    }

    window.addEventListener('click', (e) => { if (e.target === popup) popup.style.display = 'none'; });

    document.getElementById('closePopup')?.addEventListener('click', () => { popup.style.display = 'none'; });

    document.getElementById('startInstall')?.addEventListener('click', async () => {
        if (deferredPrompt) {
            deferredPrompt.prompt();
            await deferredPrompt.userChoice;
            deferredPrompt = null;
            popup.style.display = 'none';
        } else if (isIOS) {
            alert(i18n[localStorage.getItem('lang') || 'fr']['popup-ios'].replace(/<[^>]*>?/gm, ''));
        }
    });
});
